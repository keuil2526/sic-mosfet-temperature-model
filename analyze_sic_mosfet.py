#!/usr/bin/env python3
"""Temperature analysis for one SCT3080KL SiC MOSFET.

CSV units: temperature in °C, voltages in V, current in A, resistance in ohm.
No measurements are generated by this script.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.optimize import curve_fit

ROOT = Path(__file__).resolve().parent
INPUT_CSV = ROOT / "data" / "temperature_measurements.csv"
OUTPUT_DIR = ROOT / "outputs"

# Match these settings to the actual measurement protocol.
VTH_CURRENT_A = 0.010
RDS_VGS_TARGET_V = 10.0
RDS_VGS_TOLERANCE_V = 0.25
MIN_POINTS_FOR_FIT = 3


def load_data(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Missing input CSV: {path}")
    df = pd.read_csv(path)
    required = {"temperature_C", "curve_type", "vgs_V", "vds_V", "id_A"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns: {sorted(missing)}")
    if df.empty:
        raise ValueError("CSV has no measurement rows. Add real measurements first.")
    for col in ["temperature_C", "vgs_V", "vds_V", "id_A"]:
        df[col] = pd.to_numeric(df[col], errors="coerce")
    if "rds_on_ohm" not in df:
        df["rds_on_ohm"] = np.nan
    else:
        df["rds_on_ohm"] = pd.to_numeric(df["rds_on_ohm"], errors="coerce")
    df["curve_type"] = df["curve_type"].astype(str).str.strip().str.lower()
    if df["temperature_C"].isna().any():
        raise ValueError("temperature_C contains blank or invalid values.")
    if (df["temperature_C"] <= -273.15).any():
        raise ValueError("Temperature must be above absolute zero.")
    allowed = {"transfer", "output", "rds_on"}
    bad = sorted(set(df["curve_type"]) - allowed)
    if bad:
        raise ValueError(f"Unknown curve_type {bad}; use transfer, output, or rds_on.")
    return df


def save_plot(path: Path) -> None:
    plt.tight_layout()
    plt.savefig(path, dpi=180, bbox_inches="tight")
    plt.close()


def plot_curves(df: pd.DataFrame) -> dict[str, int]:
    counts = {}
    specs = [
        ("transfer", "transfer_curves.png", "vgs_V", "Gate-source voltage VGS (V)"),
        ("output", "output_curves.png", "vds_V", "Drain-source voltage VDS (V)"),
    ]
    for kind, filename, xcol, xlabel in specs:
        sub = df[df["curve_type"] == kind].dropna(subset=[xcol, "id_A"])
        counts[kind] = int(len(sub))
        if sub.empty:
            logging.info("No %s data; skipping plot.", kind)
            continue
        plt.figure(figsize=(8, 5))
        for temp, group in sub.groupby("temperature_C"):
            group = group.sort_values(xcol)
            plt.plot(group[xcol], group["id_A"], marker="o", label=f"{temp:g} °C")
        plt.xlabel(xlabel)
        plt.ylabel("Drain current ID (A)")
        plt.title(f"SCT3080KL {kind.capitalize()} Curves")
        plt.grid(True, alpha=0.3)
        plt.legend(title="Temperature")
        save_plot(OUTPUT_DIR / filename)
    return counts


def extract_vth(df: pd.DataFrame) -> pd.DataFrame:
    transfer = df[df["curve_type"] == "transfer"].dropna(subset=["vgs_V", "id_A"])
    rows: list[dict[str, Any]] = []
    for temp, group in transfer.groupby("temperature_C"):
        curve = group.groupby("vgs_V", as_index=False)["id_A"].mean().sort_values("vgs_V")
        vgs = curve["vgs_V"].to_numpy(float)
        ids = curve["id_A"].to_numpy(float)
        crossings = np.where((ids[:-1] - VTH_CURRENT_A) * (ids[1:] - VTH_CURRENT_A) <= 0)[0]
        crossings = [i for i in crossings if ids[i] != ids[i + 1]]
        if crossings:
            i = crossings[0]
            vth = vgs[i] + (VTH_CURRENT_A - ids[i]) * (vgs[i + 1] - vgs[i]) / (ids[i + 1] - ids[i])
            method = "linear interpolation at current criterion"
        else:
            logging.warning("No Vth crossing at %.4g A for %.3g °C.", VTH_CURRENT_A, temp)
            continue
        rows.append({"temperature_C": float(temp), "threshold_current_A": VTH_CURRENT_A,
                     "vth_estimate_V": float(vth), "points_in_curve": int(len(curve)),
                     "method": method})
    result = pd.DataFrame(rows)
    result.to_csv(OUTPUT_DIR / "vth_by_temperature.csv", index=False)
    if result.empty:
        logging.warning("No Vth extracted. Check transfer data and VTH_CURRENT_A.")
    return result


def extract_rds_on(df: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for temp, group in df.groupby("temperature_C"):
        direct = group[(group["curve_type"] == "rds_on") & (group["rds_on_ohm"] > 0)]
        if not direct.empty:
            vals = direct["rds_on_ohm"].dropna().to_numpy(float)
            if len(vals):
                rows.append({"temperature_C": float(temp), "rds_on_ohm": float(np.median(vals)),
                             "n_points": int(len(vals)), "method": "direct measurement median",
                             "vgs_target_V": RDS_VGS_TARGET_V})
                continue
        sub = group[group["curve_type"].isin(["output", "rds_on"])].dropna(
            subset=["vgs_V", "vds_V", "id_A"])
        sub = sub[(sub["id_A"] > 0) & (sub["vds_V"] > 0) &
                  ((sub["vgs_V"] - RDS_VGS_TARGET_V).abs() <= RDS_VGS_TOLERANCE_V)]
        if sub.empty:
            continue
        values = (sub["vds_V"] / sub["id_A"]).to_numpy(float)
        values = values[np.isfinite(values) & (values > 0)]
        if len(values):
            rows.append({"temperature_C": float(temp), "rds_on_ohm": float(np.median(values)),
                         "n_points": int(len(values)),
                         "method": "VDS/ID proxy; validate low-VDS ohmic region",
                         "vgs_target_V": RDS_VGS_TARGET_V})
    result = pd.DataFrame(rows)
    result.to_csv(OUTPUT_DIR / "rds_on_by_temperature.csv", index=False)
    if result.empty:
        logging.warning("No RDS(on) found. Add direct rds_on_ohm measurements or suitable output data.")
    return result


def fit_vth(vth: pd.DataFrame) -> dict[str, Any] | None:
    if vth["temperature_C"].nunique() < MIN_POINTS_FOR_FIT:
        logging.warning("Skipping Vth fit: need at least %d distinct temperatures.", MIN_POINTS_FOR_FIT)
        return None
    x = vth["temperature_C"].to_numpy(float)
    y = vth["vth_estimate_V"].to_numpy(float)
    slope, intercept = np.polyfit(x, y, 1)
    pred = slope * x + intercept
    ss_res = float(np.sum((y - pred) ** 2))
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    r2 = float(1 - ss_res / ss_tot) if ss_tot > 0 else None
    plt.figure(figsize=(7, 5))
    plt.scatter(x, y, label="Extracted data")
    order = np.argsort(x)
    plt.plot(x[order], pred[order], label="Linear fit")
    plt.xlabel("Temperature (°C)")
    plt.ylabel("Estimated Vth (V)")
    plt.title("Threshold Voltage vs Temperature")
    plt.grid(True, alpha=0.3)
    plt.legend()
    save_plot(OUTPUT_DIR / "vth_temperature_fit.png")
    return {"equation": "Vth(T_C) = slope * T_C + intercept", "slope_V_per_C": float(slope),
            "intercept_V": float(intercept), "r_squared": r2,
            "n_temperatures": int(vth["temperature_C"].nunique())}


def fit_rds(rds: pd.DataFrame) -> dict[str, Any] | None:
    t_c = rds["temperature_C"].to_numpy(float)
    y = rds["rds_on_ohm"].to_numpy(float)
    valid = np.isfinite(t_c) & np.isfinite(y) & (y > 0) & (t_c + 273.15 > 0)
    t_c, y = t_c[valid], y[valid]
    if len(np.unique(t_c)) < MIN_POINTS_FOR_FIT:
        logging.warning("Skipping RDS(on) fit: need at least %d valid temperatures.", MIN_POINTS_FOR_FIT)
        return None
    t_k = t_c + 273.15
    t0_k = float(np.median(t_k))
    model = lambda tk, r0, exponent: r0 * (tk / t0_k) ** exponent
    try:
        params, _ = curve_fit(model, t_k, y, p0=[float(np.median(y)), 1.0],
                              bounds=([1e-12, -10], [np.inf, 10]), maxfev=20000)
    except (RuntimeError, ValueError) as exc:
        logging.warning("RDS(on) fit failed: %s", exc)
        return None
    r0, exponent = map(float, params)
    pred = model(t_k, r0, exponent)
    ss_res = float(np.sum((y - pred) ** 2))
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    r2 = float(1 - ss_res / ss_tot) if ss_tot > 0 else None
    plt.figure(figsize=(7, 5))
    plt.scatter(t_c, y, label="Measured/estimated data")
    grid_c = np.linspace(t_c.min(), t_c.max(), 200)
    plt.plot(grid_c, model(grid_c + 273.15, r0, exponent), label="Power-law fit")
    plt.xlabel("Temperature (°C)")
    plt.ylabel("RDS(on) (ohm)")
    plt.title("On-Resistance vs Temperature")
    plt.grid(True, alpha=0.3)
    plt.legend()
    save_plot(OUTPUT_DIR / "rds_on_temperature_fit.png")
    return {"equation": "RDS(T_K) = R0 * (T_K / T0_K)^m", "reference_temperature_K": t0_k,
            "R0_ohm_at_reference_temperature": r0, "exponent_m": exponent, "r_squared": r2,
            "n_temperatures": int(len(np.unique(t_c)))}


def analyze_gm(df: pd.DataFrame) -> dict[str, str] | None:
    sub = df[df["curve_type"] == "transfer"].dropna(subset=["vgs_V", "id_A"])
    rows = []
    for temp, group in sub.groupby("temperature_C"):
        curve = group.groupby("vgs_V", as_index=False)["id_A"].mean().sort_values("vgs_V")
        if len(curve) < 3:
            continue
        gm = np.gradient(curve["id_A"].to_numpy(float), curve["vgs_V"].to_numpy(float))
        rows.extend({"temperature_C": float(temp), "vgs_V": float(vg), "gm_S": float(g)}
                    for vg, g in zip(curve["vgs_V"], gm))
    if not rows:
        logging.warning("Skipping gm: each transfer curve needs at least 3 distinct VGS values.")
        return None
    out = pd.DataFrame(rows)
    out.to_csv(OUTPUT_DIR / "gm_by_temperature.csv", index=False)
    plt.figure(figsize=(8, 5))
    for temp, group in out.groupby("temperature_C"):
        plt.plot(group["vgs_V"], group["gm_S"], marker="o", label=f"{temp:g} °C")
    plt.xlabel("VGS (V)")
    plt.ylabel("Numerical gm (S)")
    plt.title("Numerically Estimated Transconductance")
    plt.grid(True, alpha=0.3)
    plt.legend(title="Temperature")
    save_plot(OUTPUT_DIR / "gm_by_temperature.png")
    return {"method": "numerical derivative dID/dVGS",
            "warning": "gm is not a direct measurement of carrier mobility."}


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    df = load_data(INPUT_CSV)
    logging.info("Loaded %d rows; temperatures: %s °C", len(df),
                 sorted(df["temperature_C"].unique().tolist()))
    curve_counts = plot_curves(df)
    vth = extract_vth(df)
    rds = extract_rds_on(df)
    vth_fit = fit_vth(vth) if not vth.empty else None
    rds_fit = fit_rds(rds) if not rds.empty else None
    gm = analyze_gm(df)
    summary = {
        "device_scope": "single device; no Planar-versus-Trench inference",
        "measurement_rows": int(len(df)),
        "temperatures_C": sorted(float(x) for x in df["temperature_C"].unique()),
        "curve_row_counts": curve_counts,
        "settings": {"vth_current_A": VTH_CURRENT_A,
                     "rds_vgs_target_V": RDS_VGS_TARGET_V,
                     "rds_vgs_tolerance_V": RDS_VGS_TOLERANCE_V,
                     "minimum_temperatures_for_fit": MIN_POINTS_FOR_FIT},
        "vth_linear_fit": vth_fit,
        "rds_on_power_law_fit": rds_fit,
        "gm_analysis": gm,
        "warnings": [
            "Vth depends on the chosen drain-current criterion and measurement setup.",
            "VDS/ID estimates RDS(on) only under suitable low-VDS ohmic-region conditions.",
            "Temperature fits are empirical and should not be extrapolated outside measured temperatures.",
            "A single device cannot establish device-to-device variation or compare device structures.",
            "Numerical gm is not, by itself, a direct carrier-mobility measurement."
        ]
    }
    with (OUTPUT_DIR / "summary.json").open("w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)
    logging.info("Finished. Results saved in %s", OUTPUT_DIR)


if __name__ == "__main__":
    main()
